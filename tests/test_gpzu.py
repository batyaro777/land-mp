def parcel(**kw):
    base = {
        "cad_num": "39:17:010012:45",
        "permitted_use": "под жилую застройку индивидуальную",
        "permitted_use_tab": [],
        "territorial_zones": [],
        "zouit": [{"reg_number": "39:00-6.802", "name": "ЗСО третий пояс"}],
    }
    base.update(kw)
    return base


def test_parse_header_zone_vri_params_and_zouit():
    g = gpzu.parse(GPZU_TEXT)
    assert g.is_gpzu and g.number == "РФ-39-2-04-0-00-2026-0117"
    assert g.cad_num == "39:17:010012:45" and g.area_m2 == 1200.0 and g.issued == "14.03.2026"
    assert g.location.startswith("Калининградская область, Светлогорский")
    assert g.issuer.startswith("Агентство по архитектуре")
    assert g.zone_code == "Ж-4" and "индивидуальными жилыми" in g.zone_name
    assert "решением от 22.12.2012 № 94" in g.pzz_act
    assert g.codes_main == ["2.1", "2.2", "2.3"] and g.codes_conditional == ["4.4", "4.7"]
    assert g.vri_aux == ["Хранение автотранспорта (2.7.1)"]
    assert g.setbacks == "3 м" and g.floors.startswith("3") and g.height == "12 м"
    assert g.coverage_pct == "40 %"
    regs = {z["reg_number"] for z in g.zouit}
    assert regs == {"39:00-6.802", "39.00.2.44"} and any("Храброво" in z["name"] for z in g.zouit)
    assert g.red_lines is False
    assert g.code_notes and "код 2.1" in g.code_notes[0]
    assert "заявления правообладателя" not in str(g.to_dict())  # ФИО и заявление не храним
    assert gpzu.parse("Выписка из ЕГРН об объекте недвижимости").is_gpzu is False


def test_compare_ok_when_everything_matches():
    g = gpzu.parse(GPZU_TEXT)
    rows = gpzu.compare(g, parcel())
    by = {r["field"]: r for r in rows}
    assert by["Участок"]["level"] == "ок"
    assert by["ВРИ"]["level"] == "ок" and "входит в основные" in by["ВРИ"]["text"]
    assert by["Терзона"]["level"] == "ок" and "Ж-4" in by["Терзона"]["text"]
    assert by["ЗОУИТ"]["level"] == "проверить" and "39.00.2.44" in by["ЗОУИТ"]["text"]
    assert by["Срок"]["level"] == "ок"


def test_compare_flags_mismatches():
    g = gpzu.parse(GPZU_TEXT)
    p = parcel(
        cad_num="39:17:010012:46",
        permitted_use="Магазины",
        territorial_zones=[{"name": "Ж-1", "kind": "Зона застройки ИЖС"}],
        zouit=[{"reg_number": "39:00-6.802"}, {"reg_number": "39.00.2.44"}],
    )
    by = {r["field"]: r for r in gpzu.compare(g, p)}
    assert by["Участок"]["level"] == "стоп"
    assert by["ВРИ"]["level"] == "проверить" and "условно" in by["ВРИ"]["text"]
    assert by["Терзона"]["level"] == "проверить" and "Ж-1" in by["Терзона"]["text"]
    assert by["ЗОУИТ"]["level"] == "ок"
    old = gpzu.parse(GPZU_TEXT.replace("Дата выдачи 14.03.2026", "Дата выдачи 01.02.2021"))
    assert {r["field"]: r for r in gpzu.compare(old, parcel())}["Срок"]["level"] == "проверить"


def test_apply_to_item_replaces_flag_and_recomputes_verdict():
    g = gpzu.parse(GPZU_TEXT)
    data = {
        "parcel": parcel(),
        "flags": [{"rule_id": "R20", "level": "стоп", "message": "старый"}],
        "verdict": "стоп",
    }
    out = gpzu.apply_to_item(data, g)
    r20 = [f for f in out["flags"] if f["rule_id"] == "R20"]
    assert len(r20) == 1 and r20[0]["level"] == "проверить" and "39.00.2.44" in r20[0]["message"]
    assert out["verdict"] == "проверить" and out["gpzu"]["level"] == "проверить"
    assert out["gpzu"]["compare"] and out["gpzu"]["zone_code"] == "Ж-4"
    assert gpzu.worst([]) is Level.OK


def test_gpzu_of_picks_gpzu_document_and_keeps_filename():
    from landcheck import intake
    from landcheck.web import materials

    docs = [
        intake.Material("vypiska.pdf", b"%PDF-1.4", "pdf", text="Выписка из ЕГРН 39:17:010012:45"),
        intake.Material("gpzu.pdf", b"%PDF-1.4", "pdf", text=GPZU_TEXT),
        intake.Material("scan.pdf", b"%PDF-1.4", "pdf", text=""),
    ]
    out = materials.gpzu_of(docs)
    assert out["document"] == "gpzu.pdf" and out["zone_code"] == "Ж-4"
    assert materials.gpzu_of(docs[:1]) is None
