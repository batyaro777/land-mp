"""Ссылки на первоисточники в текстах источников флагов (ТЗ v3, п. 6; Тони, 01.11: «ссылка на
конкретную страницу, где строка или пункт первоисточника»). Коды и законы — на официальные тексты
в КонсультантПлюс (идентификаторы документов проверены 01.11.2026 по заголовкам страниц); адреса
http(s) в тексте источника (документы администрации, torgi.gov.ru) — кликабельны."""

from __future__ import annotations

import re

from markupsafe import Markup, escape

CONSULTANT = "https://www.consultant.ru/document/cons_doc_LAW_{id}/"
# (regex по тексту источника, id документа, подпись)
LAWS: tuple[tuple[str, str, str], ...] = (
    (r"(?<![А-Яа-я])ЗК(?:\s*РФ)?(?![А-Яа-я])", "33773", "Земельный кодекс РФ"),
    (r"(?<![А-Яа-я])ГрК(?:\s*РФ)?(?![А-Яа-я])", "51040", "Градостроительный кодекс РФ"),
    (r"(?<![А-Яа-я])НК(?:\s*РФ)?(?![А-Яа-я])", "28165", "Налоговый кодекс РФ, часть 2"),
    (r"(?<!\d)33-ФЗ", "6072", "33-ФЗ «Об особо охраняемых природных территориях»"),
    (r"(?<!\d)101-ФЗ", "37816", "101-ФЗ «Об обороте земель сельскохозяйственного назначения»"),
    (r"(?<!\d)7-ФЗ", "34823", "7-ФЗ «Об охране окружающей среды»"),
    (r"(?<!\d)217-ФЗ", "221173", "217-ФЗ «О ведении гражданами садоводства и огородничества»"),
    (r"(?<!\d)127-ФЗ", "39331", "127-ФЗ «О несостоятельности (банкротстве)»"),
    (r"(?<!\d)229-ФЗ", "71450", "229-ФЗ «Об исполнительном производстве»"),
    (r"(?<!\d)221-ФЗ", "70088", "221-ФЗ «О кадастровой деятельности»"),
    (r"(?<!\d)218-ФЗ", "182661", "218-ФЗ «О государственной регистрации недвижимости»"),
    (r"(?<!\d)112-ФЗ", "43127", "112-ФЗ «О личном подсобном хозяйстве»"),
    (r"(?<!\d)171-ФЗ", "164516", "171-ФЗ от 23.06.2014 (изменения в ЗК РФ)"),
    (r"(?<!\d)505-ФЗ", "372675", "505-ФЗ от 30.12.2020 (населённые пункты в ООПТ)"),
)
_URL_RE = re.compile(r"https?://[^\s<>\"'»)]+")
_COMPILED = [(re.compile(rx), CONSULTANT.format(id=doc_id), title) for rx, doc_id, title in LAWS]


def law_links(text: str | None) -> Markup:
    """Текст источника → HTML: ссылки на законы и кликабельные адреса. Текст экранируется."""
    if not text:
        return Markup("")
    s = str(escape(text))
    # адреса — первыми, чтобы внутри них не искать «ЗК»
    parts: list[str] = []
    last = 0
    for m in _URL_RE.finditer(s):
        parts.append(_linkify_laws(s[last : m.start()]))
        url = m.group(0)
        parts.append(f'<a href="{url}" target="_blank" rel="noopener">{url}</a>')
        last = m.end()
    parts.append(_linkify_laws(s[last:]))
    return Markup("".join(parts))


def _linkify_laws(s: str) -> str:
    for rx, url, title in _COMPILED:
        s = rx.sub(
            lambda m, url=url, title=title: (
                f'<a href="{url}" target="_blank" rel="noopener" title="{title}">{m.group(0)}</a>'
            ),
            s,
        )
    return s
