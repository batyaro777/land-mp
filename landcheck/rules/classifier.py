def _from_entry(e: Entry, how: str, wording: str, note: str | None = None) -> Match:
    return Match(
        code=e.code,
        name=e.name,
        desc=e.desc,
        how=how,
        wording=wording.strip(),
        legacy=how in ("legacy", "fuzzy"),
        note=note,
        limits=limits_for(e.code),
    )


def match(text: str | None) -> Match | None:
    """Одна формулировка ВРИ → код классификатора или None."""
    if not text or not text.strip():
        return None
    codes = by_code()
    for m in _CODE_RE.finditer(text):
        e = codes.get(m.group(1))
        if e is not None:
            return _from_entry(e, "code", text)
    names = _by_name()
    norm, stem = _norm(text), _stem(text)
    stem_np = _stem(_PAREN_RE.sub("", text))
    if stem == "садоводство" and "13.2" in codes:
        # «для садоводства» без кода — садовый участок по 217-ФЗ ст. 54 ч. 7, не промсадоводство
        return _from_entry(codes["13.2"], "legacy", text, NOTE_SAD)
    for key in (norm, stem, stem_np):
        e = names.get(key)
        if e is not None:
            return _from_entry(e, "name", text)
    best, score = _closest(stem)
    if best is not None and score >= NAME_MIN:
        # то же наименование в другом падеже или числе: «сельскохозяйственного использования»
        return _from_entry(best, "name", text)
    for rx, code, note in _LEGACY_RE:
        if rx.search(norm):
            e = codes.get(code)
            if e is not None:
                return _from_entry(e, "legacy", text, note)
    if best is not None and score >= FUZZY_MIN:
        return _from_entry(best, "fuzzy", text)
    return None


def split_wordings(permitted_use: str | None, tab: list[str] | None = None) -> list[str]:
    """Формулировки карточки и вкладки НСПД без повторов, в порядке появления."""
    out: list[str] = []
    seen: set[str] = set()
    for raw in [permitted_use or "", *(tab or [])]:
        for part in re.split(r"\s*\|\s*|;|\n", raw):
            p = part.strip(" .")
            if p and _norm(p) not in seen:
                seen.add(_norm(p))
                out.append(p)
    return out


def codes_for(permitted_use_all: str | None) -> list[str]:
    """Коды для движка правил: только по явному коду, наименованию или образцу (не fuzzy)."""
    out: list[str] = []
    for w in split_wordings(permitted_use_all):
        m = match(w)
        if m is not None and m.how != "fuzzy" and m.code not in out:
            out.append(m.code)
    return out


def describe(permitted_use: str | None, tab: list[str] | None = None) -> dict[str, Any] | None:
    """Сводка для карточки участка: главный код, остальные, несопоставленные формулировки."""
    wordings = split_wordings(permitted_use, tab)
    if not wordings:
        return None
    matched: list[Match] = []
    unmatched: list[str] = []
    for w in wordings:
        m = match(w)
        if m is None:
            unmatched.append(w)
        elif all(m.code != x.code for x in matched):
            matched.append(m)
    main = matched[0] if matched else None
    return {
        "main": main.to_dict() if main else None,
        "others": [m.to_dict() for m in matched[1:]],
        "unmatched": unmatched,
        "legacy": any(m.legacy for m in matched),
        "codes": [m.code for m in matched],
        "source": source(),
        "fetched": fetched(),
    }
