_CODE_RE = re.compile(r"(?<![\d.])(\d{1,2}\.\d{1,2}(?:\.\d{1,2}){0,2})(?!\.?\d)")
_PREFIX_RE = re.compile(
    r"^(?:земельные участки,?\s+(?:предназначенные\s+)?|земли,?\s+(?:предназначенные\s+)?|"
    r"для\s+|под\s+|размещени[ея]\s+)+"
)
_PAREN_RE = re.compile(r"\s*\([^)]*\)")


@dataclass(frozen=True)
class Entry:
    code: str
    name: str
    desc: str

    @property
    def group(self) -> str:
        return self.code.split(".")[0] + ".0"


@dataclass
class Match:
    code: str
    name: str
    desc: str
    how: str  # code | name | legacy | fuzzy
    wording: str  # формулировка участка, по которой подобран код
    legacy: bool
    note: str | None = None
    limits: dict[str, str] | None = None

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)


def _norm(text: str) -> str:
    t = (text or "").lower().replace("ё", "е").replace("«", "").replace("»", "").replace('"', "")
    t = re.sub(r"[;:,]+", " ", t)
    t = re.sub(r"\s+", " ", t).strip(" .")
    return t


def _stem(text: str) -> str:
    """Без вводных «для», «под», «размещение», «земельные участки, предназначенные»."""
    t = _norm(text)
    prev = None
    while prev != t:
        prev, t = t, _PREFIX_RE.sub("", t)
    t = re.sub(r"^ведения\s", "ведение ", t)
    return t.strip(" .")


@lru_cache(maxsize=1)
def _data() -> dict[str, Any]:
    return json.loads(DATA_PATH.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def entries() -> tuple[Entry, ...]:
    return tuple(Entry(i["code"], i["name"], i["desc"]) for i in _data()["items"])


@lru_cache(maxsize=1)
def by_code() -> dict[str, Entry]:
    return {e.code: e for e in entries()}


@lru_cache(maxsize=1)
def _by_name() -> dict[str, Entry]:
    out: dict[str, Entry] = {}
    for e in entries():
        for key in {_norm(e.name), _stem(e.name), _stem(_PAREN_RE.sub("", e.name))}:
            if key and key not in out:
                out[key] = e
    return out


@lru_cache(maxsize=1)
def _fuzzy_keys() -> tuple[tuple[str, Entry], ...]:
    """Ключи для сравнения по похожести: наименование целиком (скобки не снимаем, иначе
    «объектов торговли» прилипает к 4.2 «Объекты торговли (торговые центры…)»)."""
    return tuple((_stem(e.name), e) for e in entries())


def _closest(stem: str) -> tuple[Entry | None, float]:
    best, score = None, 0.0
    for key, e in _fuzzy_keys():
        r = SequenceMatcher(None, stem, key).ratio()
        if r > score:
            best, score = e, r
    return best, score


def source() -> str:
    return _data()["source"]


def fetched() -> str:
    return _data()["fetched"]


