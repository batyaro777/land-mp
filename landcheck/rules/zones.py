def zone_text(z: ZoneHit) -> str:
    """Весь текст, по которому можно узнать зону: вид, название и строковые атрибуты НСПД."""
    parts = [z.kind or "", z.name or ""]
    for k, v in z.extra.items():
        if isinstance(v, str) and k not in ("reg_numb_border", "content_restrict_encumbrances"):
            parts.append(v)
    return " ".join(p for p in parts if p).lower()


def zone_class(z: ZoneHit) -> str | None:
    t = zone_text(z)
    if not t.strip():
        return None
    for cls, keys in _NAME_CLASSES:
        if any(k in t for k in keys):
            return cls
    for pattern, cls in _CODE_FAMILIES:
        if re.search(pattern, t):
            return cls
    return None


