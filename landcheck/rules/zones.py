def zone_verdict(purpose: Purpose, cls: str | None) -> tuple[Level, str] | None:
    """Уровень и пояснение для класса зоны при заданной цели. None — цель без требований."""
    if purpose is Purpose.ANY:
        return None
    if cls is None:
        return (
            Level.CHECK,
            "код и название зоны НСПД не публикует: открыть карту градзонирования ПЗЗ "
            "муниципалитета — от зоны зависит, что здесь можно строить",
        )
    hit = ZONE_MATRIX[purpose].get(cls)
    if hit is not None:
        return hit
    default = _DEFAULT_BY_CLASS.get(cls)
    if default is not None:
        return default
    return (
        Level.CHECK,
        f"{CLASS_LABEL.get(cls, 'зона')}: допустимость цели сверить с регламентом ПЗЗ",
    )
