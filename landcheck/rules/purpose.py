def _any(t: str, *keys: str) -> bool:
    return any(k in t for k in keys)


def _is_lph(t: str) -> bool:
    return _any(t, "личного подсобного", "личное подсобное", "лпх") or _has_code(t, "2.2")


def _is_izhs(t: str) -> bool:
    return _any(t, "индивидуальн", "ижс", "индивидуального жилого") or _has_code(t, "2.1")


def _is_garden(t: str) -> bool:
    return _any(t, "ведение садоводства", "садоводств", "дачн", "садовод") or _has_code(t, "13.2")


def _is_vegetable_garden(t: str) -> bool:
    return "огородничеств" in t or _has_code(t, "13.1")


def _is_kfh(t: str) -> bool:
    return _any(t, "крестьянск", "фермерск", "кфх")


def _is_agri_production(t: str) -> bool:
    return _any(
        t,
        "сельскохозяйственного производства",
        "сельскохозяйственное производство",
        "сельскохозяйственное использование",
        "сельскохозяйственного использования",
        "растениеводств",
        "животноводств",
    ) or any(_has_code(t, f"1.{i}") for i in range(0, 21))


def vri_verdict(
    purpose: Purpose, vri_text: str, category_cls: str | None
) -> tuple[Level, str, str] | None:
    """Особые сочетания «цель × ВРИ × категория», где общая матрица слишком груба.

    Возвращает (уровень, пояснение, источник) или None — тогда действует vri_match.
    Уровень OK означает «можно, но стоит знать нюанс» — отчёт показывает это справочно.
    """
    t = (vri_text or "").lower()
    if not t.strip():
        return None
    if "общего пользования" in t:
        # Прогон Алтая 15.10: 5 из 32 участков с ВРИ «земли общего пользования» получали
        # мягкое «проверить», хотя такие участки в частную собственность не передаются.
        return (
            Level.STOP,
            "ВРИ «общего пользования»: улицы, проезды, набережные — в частную собственность "
            "не передаются, сделка купли-продажи невозможна",
            SRC_ZK85,
        )
    settlement = category_cls == "settlement"
    agri = category_cls == "agri"

    if purpose is Purpose.IZHS:
        if _is_lph(t) and not _is_izhs(t):
            if settlement:
                return (
                    Level.OK,
                    "ВРИ «ЛПХ» в населённом пункте — приусадебный участок: жилой дом строить "
                    "и регистрировать можно; это не ИЖС — условия ипотеки и льгот сверить с банком",
                    SRC_112,
                )
            if agri:
                return (
                    Level.STOP,
                    "ВРИ «ЛПХ» на сельхозземле — полевой участок: любое строительство запрещено, "
                    "только выращивание продукции",
                    SRC_112,
                )
            return (
                Level.CHECK,
                "ВРИ «ЛПХ»: дом можно только на приусадебном участке в населённом пункте — "
                "категория не распознана, уточнить",
                SRC_112,
            )
        if _is_vegetable_garden(t):
            return (
                Level.STOP,
                "ВРИ «огородничество»: капитальные строения, в том числе жилой дом, запрещены",
                SRC_217,
            )
        if _is_garden(t) and not _is_izhs(t):
            return (
                Level.CHECK,
                "ВРИ «садоводство»: жилой дом допустим по 217-ФЗ, если участок в территориальной "
                "зоне, где градрегламент разрешает капитальное строительство; проверить по ПЗЗ",
                SRC_217,
            )
        if agri and _is_kfh(t):
            return (
                Level.CHECK,
                "ВРИ «крестьянское (фермерское) хозяйство»: дом фермера возможен — один, до 3 этажей "
                "и 500 м², только при ведении КФХ и если регион не запретил; продать отдельно нельзя",
                SRC_KFH,
            )
    elif purpose is Purpose.SNT:
        if _is_vegetable_garden(t):
            return (
                Level.CHECK,
                "ВРИ «огородничество»: огород можно, садовый или жилой дом нельзя — "
                "только некапитальные хозпостройки",
                SRC_217,
            )
        if _is_lph(t) and agri:
            return (
                Level.CHECK,
                "ВРИ «ЛПХ» на сельхозземле — полевой участок: огород можно, садовый дом не построить",
                SRC_112,
            )
        if settlement and (_is_izhs(t) or _is_lph(t)):
            return (
                Level.OK,
                "ВРИ «ИЖС/ЛПХ» в населённом пункте: дом, сад и огород можно; статус участка "
                "даже выше дачного",
                SRC_112,
            )
    elif purpose is Purpose.LPH:
        if _is_izhs(t):
            return (
                Level.CHECK,
                "ВРИ «ИЖС»: огород, гараж и хозпостройки можно; содержание скота и птицы — "
                "по правилам благоустройства муниципалитета, обычно ограничено",
                "классификатор ВРИ (приказ Росреестра № П/0412), код 2.1",
            )
        if _is_garden(t) and not _is_lph(t):
            return (
                Level.CHECK,
                "ВРИ «садоводство»: огород и сад можно, содержание животных и птицы ВРИ "
                "не предусматривает",
                SRC_217,
            )
        if _is_agri_production(t) and not _is_lph(t):
            return (
                Level.CHECK,
                "ВРИ «сельхозпроизводство»: хозяйство вести можно, жилой дом не построить",
                "классификатор ВРИ (приказ Росреестра № П/0412), раздел 1",
            )
    elif purpose is Purpose.FARMING:
        if _is_lph(t) and agri:
            return (
                Level.OK,
                "ВРИ «ЛПХ» на сельхозземле — полевой участок: выращивать и держать скот можно, "
                "строить нельзя; товарная ферма потребует перевода в КФХ",
                SRC_112,
            )
    elif purpose is Purpose.MULTIFAMILY:
        if _is_izhs(t) or (_is_lph(t) and settlement):
            return (
                Level.STOP,
                "ВРИ «ИЖС/ЛПХ»: многоквартирный дом запрещён — только отдельно стоящий дом "
                "до 3 этажей без деления на квартиры",
                SRC_GRK_IZHS,
            )
    return None


def house_possible_on_agri(vri_text: str) -> str | None:
    """Исключения из «на сельхозземле дом не построить»: садовый участок (217-ФЗ) и КФХ (ст. 77 ЗК).

    Возвращает пояснение для уровня «проверить» или None, если исключения нет.
    """
    t = (vri_text or "").lower()
    if _is_vegetable_garden(t):
        return None
    if _is_garden(t):
        return (
            "земли сельхозназначения: жилой дом возможен только потому, что ВРИ — садоводство "
            "(217-ФЗ), и только если территориальная зона допускает капитальное строительство"
        )
    if _is_kfh(t):
        return (
            "земли сельхозназначения: единственный путь к дому — дом фермера на участке КФХ "
            "(ст. 77 ЗК РФ), с ограничениями по размеру и запретом продажи отдельно"
        )
    return None
