def _has_code(text: str, code: str) -> bool:
    return re.search(rf"(?<![\d.]){re.escape(code)}(?![\d])", text) is not None


def vri_match(purpose: Purpose, vri_text: str) -> str:
    """'match' | 'conflict' | 'unknown' | 'empty'."""
    t = (vri_text or "").lower()
    if not t.strip():
        return "empty"
    words, codes = VRI_POSITIVE[purpose]
    positive = any(w in t for w in words) or any(_has_code(t, c) for c in codes)
    if positive:
        return "match"
    if any(w in t for w in VRI_NEGATIVE[purpose]):
        return "conflict"
    return "unknown"


