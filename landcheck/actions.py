def action_plan(item: dict[str, Any]) -> dict[str, Any]:
    """План по флагам «стоп» и «проверить» отчёта: шаги по каждому флагу и единый список документов."""
    steps: list[dict[str, Any]] = []
    docs: dict[str, str] = {}
    for f in item.get("flags") or []:
        if f.get("level") not in ("стоп", "проверить"):
            continue
        plan = PLANS.get(f.get("rule_id") or "")
        if plan is None:
            continue
        actions = plan(f) if callable(plan) else plan
        for a in actions:
            if a.get("doc"):
                docs.setdefault(a["doc"], a["doc_where"])
        steps.append(
            {
                "rule_id": f["rule_id"],
                "level": f["level"],
                "message": f.get("message", ""),
                "actions": [
                    {"what": a["what"], "where": a["where"], "next": a["next"]} for a in actions
                ],
            }
        )
    order = {"стоп": 0, "проверить": 1}
    steps.sort(key=lambda s: order.get(s["level"], 2))
    return {
        "steps": steps,
        "documents": [{"name": k, "where": v} for k, v in docs.items()],
    }
