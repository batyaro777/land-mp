def _plan_r10(f: dict[str, Any]) -> list[Step]:
    zones = (f.get("details") or {}).get("zouit") or []
    out: list[Step] = []
    for z in zones:
        text = f"{z.get('kind') or ''} {z.get('name') or ''}".lower()
        step = next((s for needles, s in ZOUIT_PLANS if any(n in text for n in needles)), None)
        step = step or ZOUIT_DEFAULT
        if step not in out:
            out.append(step)
    return out or [ZOUIT_DEFAULT]


