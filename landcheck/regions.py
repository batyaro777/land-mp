_CAD_RE = re.compile(r"\b(\d{2}):\d{2}:\d{6,7}:\d+\b")


def region_from_cadnum(text: str) -> str | None:
    """«… 90:12:010101:25 …» → «Республика Крым»; при нескольких номерах — регион первого."""
    m = _CAD_RE.search(text or "")
    return CADASTRAL_REGIONS.get(m.group(1)) if m else None
